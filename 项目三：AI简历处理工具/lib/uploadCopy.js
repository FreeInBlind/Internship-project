export function uploadMessage(message, language) {
  if (language !== 'en') return message;
  if (englishMessages[message]) return englishMessages[message];
  const page = message.match(/^正在(处理|识别)第 (\d+)\/(\d+) 页…$/);
  if (page) return `${page[1] === '处理' ? 'Processing' : 'Recognizing'} page ${page[2]}/${page[3]}…`;
  return 'Processing the document…';
}
